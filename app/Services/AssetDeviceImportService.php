<?php

namespace App\Services;

use App\Models\AssetInventory\AssetDevice;
use Illuminate\Support\Facades\DB;

class AssetDeviceImportService
{
    /**
     * Insert validated rows, skipping duplicates by asset_tag or serial_number.
     *
     * @param  array<int, array<string, mixed>>  $rows  Validated rows (see ImportAssetDevicesRequest).
     * @return array{imported: int, skipped: array<int, array{row: int, asset_tag: string, reason: string}>}
     */
    public function import(array $rows): array
    {
        $assetTags = collect($rows)->pluck('asset_tag')->filter()->unique()->values();
        $serials = collect($rows)->pluck('serial_number')->filter()->unique()->values();

        $existingTags = AssetDevice::withTrashed()
            ->whereIn('asset_tag', $assetTags)
            ->pluck('asset_tag')
            ->flip();

        $existingSerials = $serials->isEmpty()
            ? collect()
            : AssetDevice::withTrashed()
                ->whereIn('serial_number', $serials)
                ->pluck('serial_number')
                ->flip();

        $now = now();
        $toInsert = [];
        $skipped = [];
        $seenTags = [];
        $seenSerials = [];

        foreach ($rows as $index => $row) {
            $tag = trim($row['asset_tag']);
            $serial = isset($row['serial_number']) ? trim((string) $row['serial_number']) : null;
            $serial = $serial === '' ? null : $serial;

            if (isset($existingTags[$tag]) || isset($seenTags[$tag])) {
                $skipped[] = ['row' => $index + 1, 'asset_tag' => $tag, 'reason' => 'Duplicate asset tag'];
                continue;
            }

            if ($serial !== null && (isset($existingSerials[$serial]) || isset($seenSerials[$serial]))) {
                $skipped[] = ['row' => $index + 1, 'asset_tag' => $tag, 'reason' => 'Duplicate serial number'];
                continue;
            }

            $seenTags[$tag] = true;
            if ($serial !== null) {
                $seenSerials[$serial] = true;
            }

            $toInsert[] = [
                'asset_tag' => $tag,
                'serial_number' => $serial,
                'device_type' => $row['device_type'],
                'brand' => trim($row['brand']),
                'model' => $row['model'] ?? null,
                'status' => $row['status'],
                'availability' => $row['availability'],
                'condition' => $row['condition'] ?? null,
                'nature' => $row['nature'] ?? null,
                'price' => $row['price'] ?? null,
                'purchase_date' => $row['purchase_date'] ?? null,
                'account' => $row['account'] ?? null,
                'issued_to' => $row['issued_to'] ?? null,
                'received_by' => $row['received_by'] ?? null,
                'location' => $row['location'] ?? null,
                'site' => $row['site'] ?? null,
                'notes' => $row['notes'] ?? null,
                'imported_at' => $now,
                'created_at' => $now,
                'updated_at' => $now,
            ];
        }

        // uuid is generated by the model's creating hook, so use per-row create()
        // inside a transaction rather than a raw bulk insert.
        DB::transaction(function () use ($toInsert) {
            foreach (array_chunk($toInsert, 100) as $chunk) {
                foreach ($chunk as $attributes) {
                    AssetDevice::create($attributes);
                }
            }
        });

        return [
            'imported' => count($toInsert),
            'skipped' => $skipped,
        ];
    }
}
